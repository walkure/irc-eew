// Command gen is a one-off generator that mechanically converts the Perl
// lookup tables in lib/Earthquake/EEW/Decoder.pm into a Go source file
// (internal/decoder/tables_gen.go), so the ~600 combined table entries
// (many large Japanese place-name tables) don't have to be hand-transcribed
// and risk silent typos in real disaster-notification text.
//
// Usage (run once, output is committed as normal source, not regenerated
// automatically at build time — see the plan's rationale for treating this
// as a vendored/reviewed snapshot rather than a build-time fetch):
//
//	go run ./internal/decoder/gen -in ../../../lib/Earthquake/EEW/Decoder.pm -out ../tables_gen.go
package main

import (
	"flag"
	"fmt"
	"log/slog"
	"os"
	"regexp"
	"sort"
	"strings"
)

// tables lists the Perl hash variable names to extract, in the order they
// should appear in the generated Go file, along with the Go identifier to
// emit each as.
var tables = []struct {
	perlName string
	goName   string
}{
	{"code_type", "CodeType"},
	{"section", "Section"},
	{"msg_type", "MsgType"},
	{"NCN_type", "NCNType"},
	{"shindo", "Shindo"},
	{"rk1", "RK1"},
	{"rk2", "RK2"},
	{"rk3", "RK3"},
	{"rt1", "RT1"},
	{"rc1", "RC1"},
	{"rc2", "RC2"},
	{"ebiy1", "EBIY1"},
	{"ebiy2", "EBIY2"},
	{"warn_type", "WarnType"},
	{"epicenter_code", "EpicenterCode"},
	{"area_code", "AreaCode"},
}

// matches one "key => 'value'," entry line. Keys are either single-quoted
// Perl strings or bare words/numbers (Perl allows unquoted hash keys).
var entryRE = regexp.MustCompile(`^\s*(?:'([^']*)'|([A-Za-z0-9_/]+))\s*=>\s*'([^']*)'\s*,?\s*$`)

func main() {
	slog.SetDefault(slog.New(slog.NewTextHandler(os.Stdout, nil)))

	in := flag.String("in", "", "path to Decoder.pm")
	out := flag.String("out", "", "path to write the generated Go file")
	flag.Parse()
	if *in == "" || *out == "" {
		slog.Error("both -in and -out are required")
		os.Exit(1)
	}

	src, err := os.ReadFile(*in)
	if err != nil {
		slog.Error("reading source", "path", *in, "error", err)
		os.Exit(1)
	}
	lines := strings.Split(string(src), "\n")

	var b strings.Builder
	b.WriteString("// Code generated by internal/decoder/gen from lib/Earthquake/EEW/Decoder.pm. DO NOT EDIT.\n")
	b.WriteString("// Regenerate with: go run ./internal/decoder/gen -in <path-to-Decoder.pm> -out internal/decoder/tables_gen.go\n\n")
	b.WriteString("package decoder\n\n")

	for _, tbl := range tables {
		entries, err := extractTable(lines, tbl.perlName)
		if err != nil {
			slog.Error("extracting table", "table", tbl.perlName, "error", err)
			os.Exit(1)
		}
		if len(entries) == 0 {
			slog.Error("no entries found (check the extraction regex against the source)", "table", tbl.perlName)
			os.Exit(1)
		}
		fmt.Fprintf(&b, "// %s has %d entries, extracted from Perl %%%s.\n", tbl.goName, len(entries), tbl.perlName)
		fmt.Fprintf(&b, "var %s = map[string]string{\n", tbl.goName)
		keys := make([]string, 0, len(entries))
		for k := range entries {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			fmt.Fprintf(&b, "\t%q: %q,\n", k, entries[k])
		}
		b.WriteString("}\n\n")
		slog.Info("extracted table", "table", tbl.perlName, "entries", len(entries))
	}

	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		slog.Error("writing output", "path", *out, "error", err)
		os.Exit(1)
	}
}

// extractTable finds "my %<name> = (" and reads entries until the matching
// closing ");" line.
func extractTable(lines []string, name string) (map[string]string, error) {
	start := -1
	openRE := regexp.MustCompile(`^\s*my\s+%` + regexp.QuoteMeta(name) + `\s*=\s*\(\s*$`)
	for i, l := range lines {
		if openRE.MatchString(l) {
			start = i + 1
			break
		}
	}
	if start < 0 {
		return nil, fmt.Errorf("opening line 'my %%%s = (' not found", name)
	}

	entries := map[string]string{}
	for i := start; i < len(lines); i++ {
		l := lines[i]
		trimmed := strings.TrimSpace(l)
		if trimmed == ");" {
			return entries, nil
		}
		m := entryRE.FindStringSubmatch(l)
		if m == nil {
			if trimmed == "" || strings.HasPrefix(trimmed, "#") {
				continue
			}
			return nil, fmt.Errorf("line %d: could not parse entry: %q", i+1, l)
		}
		key := m[1]
		if key == "" {
			key = m[2]
		}
		entries[key] = m[3]
	}
	return nil, fmt.Errorf("closing ');' not found for table %s", name)
}
